export type ParsedQuestion = {
  id: string
  prompt: string
  options: [string, string]
  correctIndex: 0 | 1
  explanation: string
  status: 'approved'
  authoringFile: string
  approvalUrl: string
}

const approvalLink =
  /\[[^\]]*\]\((https:\/\/github\.com\/Vedrana\/pravopisac\/pull\/\d+#[^)\s]+)\)/
const approvedByHuman = /approved by @\w+/i
const questionBlock =
  /^ID: (.+)\n\n(.+)\n\nA: (.+)\nB: (.+)\n\nCorrect answer: ([AB])\n\nExplanation: (.+)$/s

function section(text: string, heading: string): string | undefined {
  const start = text.indexOf(`\n## ${heading}\n`)
  if (start === -1) return undefined
  const body = text.slice(start + heading.length + 5)
  const next = body.indexOf('\n## ')
  return next === -1 ? body : body.slice(0, next)
}

function findApproval(text: string): string | undefined {
  const header = text.slice(0, text.indexOf('\n## '))
  // Accept the approval statement either at the top of the file or under Human review.
  for (const candidate of [header, section(text, 'Human review')]) {
    if (candidate && approvedByHuman.test(candidate)) {
      const link = approvalLink.exec(candidate)
      if (link) return link[1]
    }
  }
  return undefined
}

export function parseQuestionFile(
  authoringFile: string,
  text: string,
): ParsedQuestion {
  const fail = (reason: string): never => {
    throw new Error(`${authoringFile}: ${reason}`)
  }

  if (!text.startsWith('# Approved question\n')) {
    fail('must start with "# Approved question"')
  }

  const approvalUrl = findApproval(text)
  if (approvalUrl === undefined) {
    fail('has no recorded human approval with a pull request link')
  }

  const approved = section(text, 'Approved question')
  const fence = approved && /```text\n([\s\S]*?)\n```/.exec(approved)
  if (!fence) fail('has no question block under "## Approved question"')

  const match = questionBlock.exec(fence![1]!.trim())
  if (!match) fail('question block does not match the expected format')
  const [, id, prompt, a, b, answer, explanation] = match!

  return {
    id: id!.trim(),
    prompt: prompt!.trim(),
    options: [a!.trim(), b!.trim()],
    correctIndex: answer === 'A' ? 0 : 1,
    explanation: explanation!.trim(),
    status: 'approved',
    authoringFile,
    approvalUrl: approvalUrl!,
  }
}

export function parseQuestionFiles(
  files: readonly { path: string; text: string }[],
): ParsedQuestion[] {
  const questions = files.map((file) => parseQuestionFile(file.path, file.text))
  const seen = new Set<string>()
  for (const question of questions) {
    if (seen.has(question.id)) {
      throw new Error(`Duplicate question ID ${question.id} in ${question.authoringFile}`)
    }
    seen.add(question.id)
  }
  return questions
}

export function renderQuestionsModule(questions: readonly ParsedQuestion[]): string {
  return [
    '// Generated by scripts/generate-questions.ts from authoring/questions. Do not edit.',
    "import type { Question } from './questions'",
    '',
    `export const generatedQuestions: readonly Question[] = ${JSON.stringify(questions, null, 2)}`,
    '',
  ].join('\n')
}
